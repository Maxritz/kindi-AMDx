import unicodedata

def runs(pred):
    out = []
    s = None
    for c in range(0x110000):
        if pred(c):
            if s is None:
                s = c
        else:
            if s is not None:
                out.append((s, c - 1))
                s = None
    if s is not None:
        out.append((s, 0x10FFFF))
    return out

L = runs(lambda c: unicodedata.category(chr(c))[0] == 'L')
M = runs(lambda c: unicodedata.category(chr(c))[0] == 'M')
N = runs(lambda c: unicodedata.category(chr(c))[0] == 'N')
SP = runs(lambda c: chr(c).isspace())
print('L runs:', len(L), 'M runs:', len(M), 'N runs:', len(N), 'SP runs:', len(SP))

with open('unitbl.inc', 'w') as f:
    f.write('// generated by gen_tables.py from CPython unicodedata\n')
    for nm, rs in (('L', L), ('M', M), ('N', N), ('SP', SP)):
        f.write('static const uint32_t %sT[][2] = {' % nm)
        f.write(','.join('{0x%x,0x%x}' % (a, b) for a, b in rs))
        f.write('};\n')
print('wrote unitbl.inc')
